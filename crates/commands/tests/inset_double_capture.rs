type TestResult<T = ()> = Result<T, Box<dyn std::error::Error>>;

// No BOM, DTD, indentation or terminal newline: this is an original native-profile
// document, not output generated by Bondline for use as its own expected value.
const DOUBLE: &[u8] = br#"<?xml version="1.0" encoding="UTF-8"?><CDXML CreationProgram="Bondline 0.1.0"><page id="1" DrawingSpace="Poster" Width="256" Height="256"><fragment id="2"><n id="3" NodeType="Element" Element="6" Charge="0" Radical="None" p="32 64" NumHydrogens="2"/><n id="4" NodeType="Element" Element="6" Charge="0" Radical="None" p="96 64" NumHydrogens="2"/><b id="5" B="3" E="4" Order="2" DoublePosition="Right"/></fragment></page></CDXML>"#;
const SINGLE: &[u8] = br#"<?xml version="1.0" encoding="UTF-8"?><CDXML CreationProgram="Bondline 0.1.0"><page id="1" DrawingSpace="Poster" Width="256" Height="256"><fragment id="2"><n id="3" NodeType="Element" Element="6" Charge="0" Radical="None" p="32 64" NumHydrogens="3"/><n id="4" NodeType="Element" Element="6" Charge="0" Radical="None" p="96 64" NumHydrogens="3"/><b id="5" B="3" E="4" Order="1" DoublePosition="Right"/></fragment></page></CDXML>"#;

fn run_python(code: &str, arguments: &[&str], input: &[u8]) -> TestResult<Vec<u8>> {
    let mut child = PythonProcess::new(
        std::env::var_os("BONDLINE_PYTHON").ok_or("pinned BONDLINE_PYTHON is required")?,
    )
    .args(["-B", "-c", code])
    .args(arguments)
    .stdin(Stdio::piped())
    .stdout(Stdio::piped())
    .stderr(Stdio::piped())
    .spawn()?;
    child
        .stdin
        .take()
        .ok_or("external consumer stdin")?
        .write_all(input)?;
    let output = child.wait_with_output()?;
    assert!(
        output.status.success(),
        "independent consumer: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    Ok(output.stdout)
}

fn consume_xml(source: &[u8], single: bool) -> TestResult {
    // Expat/Decimal checks depiction/source properties; the unchanged graph consumer
    // and external RDKit have separate graph/H/formula jobs, not placement authority.
    let code = r#"
import decimal,json,subprocess,sys,xml.parsers.expat as expat
from rdkit import Chem,rdBase
from rdkit.Chem import rdMolDescriptors
assert rdBase.rdkitVersion=='2026.09.2'
single=sys.argv[2]=='single'
h=3 if single else 2
source=sys.stdin.buffer.read()
objects=[]
p=expat.ParserCreate(namespace_separator='|')
p.SetParamEntityParsing(expat.XML_PARAM_ENTITY_PARSING_NEVER)
p.StartElementHandler=lambda name,attrs:objects.append((name,attrs))
p.Parse(source,True)
assert [name for name,_ in objects]==['CDXML','page','fragment','n','n','b']
assert objects[0][1]=={'CreationProgram':'Bondline 0.1.0'}
assert objects[1][1]=={'id':'1','DrawingSpace':'Poster','Width':'256','Height':'256'}
assert objects[2][1]=={'id':'2'}
assert [attrs for name,attrs in objects if name=='n']==[
 {'id':'3','NodeType':'Element','Element':'6','Charge':'0','Radical':'None','p':'32 64','NumHydrogens':str(h)},
 {'id':'4','NodeType':'Element','Element':'6','Charge':'0','Radical':'None','p':'96 64','NumHydrogens':str(h)}]
assert objects[-1][1]=={'id':'5','B':'3','E':'4','Order':'1' if single else '2','DoublePosition':'Right'}
for _,attrs in objects[3:5]:
 assert [decimal.Decimal(token) for token in attrs['p'].split()] in [[decimal.Decimal(32),decimal.Decimal(64)],[decimal.Decimal(96),decimal.Decimal(64)]]
raw=subprocess.run([sys.executable,'-B',sys.argv[1]],input=source,stdout=subprocess.PIPE,stderr=subprocess.PIPE,check=True)
assert json.loads(raw.stdout)==[{'id':1,'atoms':[
 {'id':1,'element':6,'position':{'x_pt':32.0,'y_pt':64.0},'isotope':None,'charge':0,'radical':'none','explicit_hydrogens':h},
 {'id':2,'element':6,'position':{'x_pt':96.0,'y_pt':64.0},'isotope':None,'charge':0,'radical':'none','explicit_hydrogens':h}],
 'bonds':[{'id':1,'begin':1,'end':2,'order':'single' if single else 'double'}]}]
molecules=Chem.MolsFromCDXML(source.decode('utf-8'),sanitize=True,removeHs=False)
assert len(molecules)==1
mol=molecules[0]
assert mol.GetNumAtoms()==2 and mol.GetNumBonds()==1
assert [atom.GetAtomicNum() for atom in mol.GetAtoms()]==[6,6]
assert [atom.GetTotalNumHs() for atom in mol.GetAtoms()]==[h,h]
assert all(atom.GetIsotope()==0 and atom.GetFormalCharge()==0 and atom.GetNumRadicalElectrons()==0 for atom in mol.GetAtoms())
assert [bond.GetBondTypeAsDouble() for bond in mol.GetBonds()]==[1.0 if single else 2.0]
assert all(str(atom.GetChiralTag())=='CHI_UNSPECIFIED' for atom in mol.GetAtoms())
assert all(str(bond.GetStereo())=='STEREONONE' for bond in mol.GetBonds())
assert rdMolDescriptors.CalcMolFormula(mol)==('C2H6' if single else 'C2H4')
assert Chem.MolToSmiles(mol)==('CC' if single else 'C=C')
"#;
    run_python(
        code,
        &[
            concat!(
                env!("CARGO_MANIFEST_DIR"),
                "/../../xtask/oracles/cdxml_graph.py"
            ),
            if single { "single" } else { "double" },
        ],
        source,
    )?;
    Ok(())
}

fn assert_document(engine: &Engine, single: bool) -> TestResult {
    let document = engine.document()?;
    assert_eq!(document.pages().len(), 1);
    let page = &document.pages()[0];
    assert_eq!(page.id().get(), 1);
    assert_eq!(page.size(), PageSize::new(256.0, 256.0)?);
    let h = if single { 3 } else { 2 };
    assert_eq!(
        serde_json::to_value(page.fragments())?,
        json!([{
            "id":1,
            "atoms":[
                {"id":1,"element":6,"position":{"x_pt":32.0,"y_pt":64.0},"isotope":null,"charge":0,"radical":"none","explicit_hydrogens":h},
                {"id":2,"element":6,"position":{"x_pt":96.0,"y_pt":64.0},"isotope":null,"charge":0,"radical":"none","explicit_hydrogens":h}],
            "bonds":[{"id":1,"begin":1,"end":2,"order":if single {"single"} else {"double"},"double_position":"right"}]
        }])
    );
    assert!(
        engine.stored_document()?.is_fully_mapped(),
        "literal native authority must remain exact-byte proof"
    );
    Ok(())
}

fn capture(engine: &mut Engine, backend: &str) -> TestResult<String> {
    let before = serde_json::to_value(engine.state())?;
    let stamp = engine.capture_stamp();
    let model = engine.stored_document()?.model_snapshot();
    let result = engine.dispatch(
        "render.capture",
        json!({
            "page_id":1,"width_px":576,"height_px":576,"backend":backend
        }),
    )?;
    assert!(!result.changed);
    assert!(result.file_operation.is_none());
    assert!(result.ui_file_operation.is_none());
    let image = result.capture.ok_or("actual registered PNG reply")?;
    assert_eq!(
        (image.width_px, image.height_px, image.mime_type),
        (576, 576, "image/png")
    );
    assert_eq!(serde_json::to_value(engine.state())?, before);
    assert!(engine.capture_stamp_matches(&stamp));
    assert!(Arc::ptr_eq(
        &model,
        &engine.stored_document()?.model_snapshot()
    ));
    Ok(image.png_base64)
}

fn refuse_dormant_capture(engine: &mut Engine, backend: &str) -> TestResult {
    let before = serde_json::to_value(engine.state())?;
    let stamp = engine.capture_stamp();
    let model = engine.stored_document()?.model_snapshot();
    let error = engine
        .dispatch(
            "render.capture",
            json!({
                "page_id":1,"width_px":576,"height_px":576,"backend":backend
            }),
        )
        .err()
        .ok_or("dormant Right on Single was silently rendered")?;
    assert_eq!(error.info().code, "unsupported_content");
    assert_eq!(serde_json::to_value(engine.state())?, before);
    assert!(engine.capture_stamp_matches(&stamp));
    assert!(Arc::ptr_eq(
        &model,
        &engine.stored_document()?.model_snapshot()
    ));
    Ok(())
}

fn consume_pixels(images: &[String]) -> TestResult {
    let code = r#"
import base64,io,json,sys
from PIL import Image
payload=json.load(sys.stdin)
frames=[]
for index,png in enumerate(payload):
 data=base64.b64decode(png,validate=True)
 assert data[:8]==b'\x89PNG\r\n\x1a\n'
 with Image.open(io.BytesIO(data)) as image:
  assert image.format=='PNG' and image.size==(576,576)
  image.load()
  frame=image.convert('RGBA')
  # Declared native page256 maps to512px with32px margin: w2,
  # axis y160 and right inset y166. Endpoint labels are outside this middle band.
  for x in range(128,192):
   for y in range(156,171):
    expected=(0,0,0,255) if y in (159,160,165,166) else (255,255,255,255)
    actual=frame.getpixel((x,y))
    assert actual==expected,(index,x,y,actual,expected)
  frames.append(frame.tobytes())
assert len(frames)==5
assert all(frame==frames[0] for frame in frames[1:]),'actual CPU/GPU/restored/reopened full RGBA differs'
"#;
    run_python(code, &[], &serde_json::to_vec(images)?)?;
    Ok(())
}

#[test]
fn native_unicode_sided_double_capture_dormant_order_history_and_save_reopen_preserve_source_and_frame()
-> TestResult {
    let directory = support::FileTestDirectory::new()?;
    let input = directory.path("source-右-λ.cdxml");
    let single_path = directory.path("dormant-右-λ.cdxml");
    let double_path = directory.path("rendered-右-λ.cdxml");
    fs::write(&input, DOUBLE)?;
    consume_xml(&fs::read(&input)?, false)?;
    let mut engine = Engine::default();
    engine.dispatch("document.open_cdxml", json!({"path":input}))?;
    assert_document(&engine, false)?;
    assert_eq!(engine.state().revision, 1);
    assert_eq!(
        (engine.state().undo_depth, engine.state().redo_depth),
        (0, 0)
    );
    assert!(!engine.state().file.dirty);
    assert_eq!(
        engine.state().file.path.as_deref(),
        fs::canonicalize(&input)?.to_str()
    );
    assert_eq!(
        serde_json::to_value(engine.state().source)?,
        json!({"format":"cdxml","byte_length":DOUBLE.len(),"modified":false})
    );
    assert_eq!(engine.stored_document()?.to_cdxml()?.as_ref(), DOUBLE);
    let original_model = engine.stored_document()?.model_snapshot();
    let mut images = vec![capture(&mut engine, "cpu")?, capture(&mut engine, "gpu")?];
    let before_noop = serde_json::to_value(engine.state())?;
    let no_op = engine.dispatch(
        "bond.set_order",
        json!({
            "expected_revision":1,"page_id":1,"fragment_id":1,"bond_id":1,
            "order":"double","hydrogen_policy":"rectify_neutral_carbon"
        }),
    )?;
    assert!(!no_op.changed);
    assert_eq!(serde_json::to_value(engine.state())?, before_noop);
    assert!(Arc::ptr_eq(
        &original_model,
        &engine.stored_document()?.model_snapshot()
    ));

    let changed = engine.dispatch(
        "bond.set_order",
        json!({
            "expected_revision":1,"page_id":1,"fragment_id":1,"bond_id":1,
            "order":"single","hydrogen_policy":"rectify_neutral_carbon"
        }),
    )?;
    assert!(changed.changed);
    assert_eq!(engine.state().revision, 2);
    assert_eq!(
        (engine.state().undo_depth, engine.state().redo_depth),
        (1, 0)
    );
    assert!(engine.state().file.dirty);
    assert_document(&engine, true)?;
    assert_eq!(
        serde_json::to_value(engine.state().source)?,
        json!({"format":"cdxml","byte_length":DOUBLE.len(),"modified":true})
    );
    assert_eq!(engine.stored_document()?.to_cdxml()?.as_ref(), SINGLE);
    refuse_dormant_capture(&mut engine, "cpu")?;
    refuse_dormant_capture(&mut engine, "gpu")?;
    let saved_single = engine.dispatch("document.save_cdxml", json!({"path":single_path}))?;
    assert!(saved_single.file_operation.is_some());
    assert!(saved_single.ui_file_operation.is_none());
    assert_eq!(engine.state().revision, 2);
    assert_eq!(
        (engine.state().undo_depth, engine.state().redo_depth),
        (1, 0)
    );
    assert!(!engine.state().file.dirty);
    assert_eq!(fs::read(&single_path)?, SINGLE);
    consume_xml(&fs::read(&single_path)?, true)?;
    let mut dormant = Engine::default();
    dormant.dispatch("document.open_cdxml", json!({"path":single_path}))?;
    assert_document(&dormant, true)?;
    assert!(!dormant.state().file.dirty);
    assert_eq!(
        (dormant.state().undo_depth, dormant.state().redo_depth),
        (0, 0)
    );
    refuse_dormant_capture(&mut dormant, "cpu")?;

    engine.dispatch("history.undo", json!({}))?;
    assert_eq!(engine.state().revision, 3);
    assert_eq!(
        (engine.state().undo_depth, engine.state().redo_depth),
        (0, 1)
    );
    assert!(engine.state().file.dirty);
    assert_document(&engine, false)?;
    assert!(Arc::ptr_eq(
        &original_model,
        &engine.stored_document()?.model_snapshot()
    ));
    images.push(capture(&mut engine, "cpu")?);
    engine.dispatch("history.redo", json!({}))?;
    assert_eq!(engine.state().revision, 4);
    assert_eq!(
        (engine.state().undo_depth, engine.state().redo_depth),
        (1, 0)
    );
    assert_document(&engine, true)?;
    assert!(!engine.state().file.dirty);
    engine.dispatch("history.undo", json!({}))?;
    assert_eq!(engine.state().revision, 5);
    assert_document(&engine, false)?;
    let saved_double = engine.dispatch("document.save_cdxml", json!({"path":double_path}))?;
    assert!(saved_double.file_operation.is_some());
    assert!(saved_double.ui_file_operation.is_none());
    assert_eq!(engine.state().revision, 5);
    assert_eq!(
        (engine.state().undo_depth, engine.state().redo_depth),
        (0, 1)
    );
    assert!(!engine.state().file.dirty);
    assert_eq!(
        engine.state().file.path.as_deref(),
        fs::canonicalize(&double_path)?.to_str()
    );
    assert_eq!(fs::read(&double_path)?, DOUBLE);
    assert_eq!(fs::read(&input)?, DOUBLE);
    assert_eq!(fs::read(&single_path)?, SINGLE);
    consume_xml(&fs::read(&double_path)?, false)?;

    let mut reopened = Engine::default();
    reopened.dispatch("document.open_cdxml", json!({"path":double_path}))?;
    assert_document(&reopened, false)?;
    assert_eq!(reopened.state().revision, 1);
    assert_eq!(
        (reopened.state().undo_depth, reopened.state().redo_depth),
        (0, 0)
    );
    assert!(!reopened.state().file.dirty);
    assert_eq!(reopened.stored_document()?.to_cdxml()?.as_ref(), DOUBLE);
    assert_eq!(
        serde_json::to_value(reopened.state().source)?,
        json!({"format":"cdxml","byte_length":DOUBLE.len(),"modified":false})
    );
    images.push(capture(&mut reopened, "cpu")?);
    images.push(capture(&mut reopened, "gpu")?);
    consume_pixels(&images)?;
    Ok(())
}
