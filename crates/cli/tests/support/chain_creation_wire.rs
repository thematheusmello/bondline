fn compare(actual: &Value, expected: &Value) -> TestResult {
    let mut a = actual.clone();
    let mut e = expected.clone();
    let aa = a["atoms"].as_array_mut().ok_or("actual atoms")?;
    let ee = e["atoms"].as_array_mut().ok_or("expected atoms")?;
    assert_eq!(aa.len(), ee.len());
    for (a, e) in aa.iter_mut().zip(ee) {
        let p = a
            .as_object_mut()
            .ok_or("atom")?
            .remove("position")
            .ok_or("position")?;
        let q = e
            .as_object_mut()
            .ok_or("atom")?
            .remove("position")
            .ok_or("position")?;
        for axis in ["x_pt", "y_pt"] {
            assert!(
                (p[axis].as_f64().ok_or("position")? - q[axis].as_f64().ok_or("position")?).abs()
                    <= 1e-9
            );
        }
    }
    assert_eq!(
        a, e,
        "all identity, H, flag, direction, order and style data exact"
    );
    Ok(())
}
