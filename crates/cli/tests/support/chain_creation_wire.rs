fn resolve<'a>(root: &'a Value, node: &'a Value) -> TestResult<&'a Value> {
    match node.get("$ref").and_then(Value::as_str) {
        Some(s) => Ok(root
            .pointer(s.strip_prefix('#').ok_or("local ref")?)
            .ok_or("schema ref")?),
        None => Ok(node),
    }
}
fn discovery(entries: &[Value], schema_key: &str) -> TestResult {
    assert_eq!(entries.len(), 39);
    assert_eq!(
        entries
            .iter()
            .map(|e| e["name"].as_str().ok_or("name"))
            .collect::<Result<BTreeSet<_>, _>>()?,
        OLD_NAMES.into_iter().chain([NAME]).collect::<BTreeSet<_>>()
    );
    let entry = entries
        .iter()
        .find(|e| e["name"] == NAME)
        .ok_or("chain entry")?;
    if schema_key == "input_schema" {
        assert_eq!(entry["read_only"], false);
    } else {
        assert_eq!(entry["annotations"]["readOnlyHint"], false);
    }
    let root = &entry[schema_key];
    assert_eq!(root["type"], "object");
    assert_eq!(root["additionalProperties"], false);
    let fields = root["properties"].as_object().ok_or("fields")?;
    let required = [
        "expected_revision",
        "page_id",
        "count",
        "angle_degrees",
        "hydrogen_policy",
        "placement",
    ]
    .into_iter()
    .collect::<BTreeSet<_>>();
    assert_eq!(
        fields.keys().map(String::as_str).collect::<BTreeSet<_>>(),
        required
    );
    assert_eq!(
        root["required"]
            .as_array()
            .ok_or("required")?
            .iter()
            .map(|v| v.as_str().ok_or("field"))
            .collect::<Result<BTreeSet<_>, _>>()?,
        required
    );
    assert_eq!(fields["count"]["minimum"].as_f64(), Some(2.0));
    assert_eq!(fields["count"]["maximum"].as_f64(), Some(64.0));
    assert_eq!(fields["angle_degrees"]["minimum"].as_f64(), Some(1.0));
    assert_eq!(fields["angle_degrees"]["maximum"].as_f64(), Some(179.0));
    assert_eq!(
        resolve(root, &fields["hydrogen_policy"])?["enum"],
        json!(["rectify_neutral_carbon"])
    );
    let placement = resolve(root, &fields["placement"])?;
    let variants = placement["oneOf"].as_array().ok_or("placements")?;
    assert_eq!(variants.len(), 2);
    let mut modes = BTreeSet::new();
    for raw in variants {
        let branch = resolve(root, raw)?;
        assert_eq!(branch["type"], "object");
        assert_eq!(branch["additionalProperties"], false);
        let p = branch["properties"].as_object().ok_or("placement fields")?;
        let mode = p["mode"]["const"].as_str().ok_or("mode")?;
        assert!(modes.insert(mode));
        let keys = match mode {
            "free" => [
                "mode",
                "begin_x_pt",
                "begin_y_pt",
                "end_x_pt",
                "end_y_pt",
                "side",
            ],
            "atom" => [
                "mode",
                "fragment_id",
                "atom_id",
                "end_x_pt",
                "end_y_pt",
                "side",
            ],
            _ => return Err("extra placement".into()),
        }
        .into_iter()
        .collect::<BTreeSet<_>>();
        assert_eq!(p.keys().map(String::as_str).collect::<BTreeSet<_>>(), keys);
        assert_eq!(
            branch["required"]
                .as_array()
                .ok_or("placement required")?
                .iter()
                .map(|v| v.as_str().ok_or("field"))
                .collect::<Result<BTreeSet<_>, _>>()?,
            keys
        );
        assert_eq!(
            resolve(root, &p["side"])?["enum"]
                .as_array()
                .ok_or("sides")?
                .iter()
                .map(|v| v.as_str().ok_or("side"))
                .collect::<Result<BTreeSet<_>, _>>()?,
            ["positive", "negative"].into_iter().collect()
        );
    }
    assert_eq!(modes, ["free", "atom"].into_iter().collect());
    Ok(())
}

