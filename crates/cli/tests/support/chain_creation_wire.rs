fn raw_check(raw: &[u8], expected: &Value) -> TestResult<std::process::Output> {
    let mut child = Process::new(python())
        .args([
            "-B",
            concat!(
                env!("CARGO_MANIFEST_DIR"),
                "/tests/support/chain_flags_check.py"
            ),
            &expected.to_string(),
        ])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .ok_or("raw checker stdin")?
        .write_all(raw)?;
    Ok(child.wait_with_output()?)
}
fn qualify_raw_checker() -> TestResult {
    let good = raw_check(PROPANE, &original_propane())?;
    assert!(
        good.status.success(),
        "{}",
        String::from_utf8_lossy(&good.stderr)
    );
    for (before, after) in [
        (" ShowTerminalCarbonLabels=\"yes\"", ""),
        (
            "ShowTerminalCarbonLabels=\"yes\"",
            "ShowTerminalCarbonLabels=\"no\"",
        ),
        ("B=\"3\" E=\"4\"", "B=\"4\" E=\"3\""),
        ("Order=\"1\"", "Order=\"2\""),
    ] {
        let bad = std::str::from_utf8(PROPANE)?.replacen(before, after, 1);
        assert_ne!(bad.as_bytes(), PROPANE);
        assert!(
            !raw_check(bad.as_bytes(), &original_propane())?
                .status
                .success(),
            "manual wrong raw property accepted"
        );
    }
    Ok(())
}
