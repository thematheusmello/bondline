#[test]
fn authenticated_benzene_attachment_preserves_integer_styles_source_and_publishes_only_real_changes()
-> TestResult {
    let dir = support::SdfTestDirectory::new()?;
    let input = dir.path("benzene-original-λ.cdxml");
    let output = dir.path("toluene-化学.cdxml");
    let opaque = dir.path("opaque-原.cdxml");
    let copy = dir.path("opaque-保存.cdxml");
    fs::write(&input, BENZENE)?;
    let raw = std::str::from_utf8(BENZENE)?.replace("<CDXML ", "<CDXML Private=\"chain-opaque\" ");
    fs::write(&opaque, raw.as_bytes())?;
    let mut session = Engine::default();
    session.dispatch("document.open_cdxml", json!({"path":input}))?;
    session.dispatch(
        "ui.selection",
        json!({"action":"set","expected_revision":1,"page_id":1,"atom_ids":[1]}),
    )?;
    let original = serde_json::to_value(session.state())?;
    graph(&original, &original_benzene())?;
    let engine: SharedEngine = Arc::new(Mutex::new(session));
    let changes = Arc::new(AtomicUsize::new(0));
    let count = Arc::clone(&changes);
    let server = LoopbackServer::bind(0, Arc::clone(&engine), move || {
        count.fetch_add(1, Ordering::SeqCst);
    })?;
    let stream = TcpStream::connect_timeout(&server.address(), Duration::from_secs(5))?;
    stream.set_read_timeout(Some(Duration::from_secs(5)))?;
    stream.set_write_timeout(Some(Duration::from_secs(5)))?;
    let mut client = BufReader::new(stream);
    assert_eq!(
        socket(&mut client, json!({"token":server.token()}))?,
        json!({"authenticated":true})
    );
    let created = socket(&mut client, request(NAME, attach(1, 1, 72.0, 192.0)))?;
    assert!(created.get("error").is_none(), "{created}");
    let created = &created["result"];
    graph(created, &toluene())?;
    assert_eq!(created["revision"], 2);
    assert_eq!(created["undo_depth"], 1);
    assert_eq!(created["ui_selection"]["atom_ids"], json!([]));
    let stable = socket(&mut client, request("document.inspect", json!({})))?["result"].clone();
    assert_eq!(
        changes.load(Ordering::SeqCst),
        1,
        "publication barrier completed before this inspect"
    );
    let noop = socket(
        &mut client,
        request(
            "bond.set_order",
            json!({"expected_revision":2,"page_id":1,"fragment_id":1,"bond_id":1,"order":"double","hydrogen_policy":"rectify_neutral_carbon"}),
        ),
    )?;
    assert_eq!(noop["result"]["changed"], false);
    let stale = socket(&mut client, request(NAME, free(1, 2)))?;
    assert_eq!(stale["error"]["code"], "stale_revision");
    assert_eq!(
        socket(&mut client, request("document.inspect", json!({})))?["result"],
        stable
    );
    assert_eq!(changes.load(Ordering::SeqCst), 1);
    let saved = socket(
        &mut client,
        request("document.save_cdxml", json!({"path":output})),
    )?;
    assert!(saved.get("error").is_none());
    assert_eq!(saved["result"]["file"]["dirty"], false);
    consume(&output, &toluene(), "c1ccccc1C", "C7H8")?;
    let undo = socket(&mut client, request("history.undo", json!({})))?;
    graph(&undo["result"], &original_benzene())?;
    assert_eq!(undo["result"]["source"]["modified"], false);
    assert_eq!(undo["result"]["file"]["dirty"], true);
    let redo = socket(&mut client, request("history.redo", json!({})))?;
    graph(&redo["result"], &toluene())?;
    assert_eq!(redo["result"]["file"]["dirty"], false);
    assert_eq!(fs::read(&input)?, BENZENE);
    let opened = socket(
        &mut client,
        request("document.open_cdxml", json!({"path":output})),
    )?;
    graph(&opened["result"], &toluene())?;
    assert_eq!(opened["result"]["source"]["modified"], false);
    assert_eq!(opened["result"]["undo_depth"], 0);
    let opened = socket(
        &mut client,
        request("document.open_cdxml", json!({"path":opaque})),
    )?;
    assert!(opened.get("error").is_none());
    let before = socket(&mut client, request("document.inspect", json!({})))?["result"].clone();
    let (whole, stamp) = {
        let guard = engine.lock().map_err(|_| "engine")?;
        (guard.content().clone(), guard.capture_stamp())
    };
    let callbacks = changes.load(Ordering::SeqCst);
    let refused = socket(
        &mut client,
        request(
            NAME,
            free(before["revision"].as_u64().ok_or("revision")?, 3),
        ),
    )?;
    assert_eq!(refused["error"]["code"], "unsupported_content");
    assert_eq!(
        socket(&mut client, request("document.inspect", json!({})))?["result"],
        before
    );
    assert_eq!(changes.load(Ordering::SeqCst), callbacks);
    {
        let guard = engine.lock().map_err(|_| "engine")?;
        assert_eq!(guard.content(), &whole);
        assert!(guard.capture_stamp_matches(&stamp));
    }
    let saved = socket(
        &mut client,
        request("document.save_cdxml", json!({"path":copy})),
    )?;
    assert!(saved.get("error").is_none());
    assert_eq!(fs::read(&opaque)?, raw.as_bytes());
    assert_eq!(fs::read(&copy)?, raw.as_bytes());
    server.shutdown()?;
    Ok(())
}
